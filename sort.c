#include "push_swap.h"

/*
** 원소 개수에 따라 알맞은 정렬 방식을 고른다.
** 작은 입력은 전용 함수로 최적에 가까운 연산 수를 내고,
** 큰 입력은 이후 청크 알고리즘으로 처리한다.
*/
void	sort_stack(t_machine *m)
{
	if (m->a.size == 2)
	{
		sort_two(m);
	}
	else if (m->a.size == 3)
	{
		sort_three(m);
	}
	else if (m->a.size <= 5)
	{
		sort_four_five(m);
	}
	else
	{
		sort_big(m);
	}
}
